export type ProspectSegmentType = (typeof PROSPECT_SEGMENTS)[number]["type"]

const SEGMENT_TYPES = new Set<string>(
  PROSPECT_SEGMENTS.map((segment) => segment.type)
)

export function isProspectSegmentType(
  value: string
): value is ProspectSegmentType {
  return SEGMENT_TYPES.has(value)
}

export function getProspectSegmentLabel(type: string) {
  return (
    PROSPECT_SEGMENTS.find((segment) => segment.type === type)?.label ?? type
  )
}
